def choose(kind,event,used,topic=''):
    starts,ends=(PASS_START,PASS_END) if kind=='pass' else (SIGN_START,SIGN_END)
    count=len(starts)*len(ends)
    seed=int.from_bytes(hashlib.sha256(event.encode()).digest()[:8],'big')
    # The topic creates independent sets for each lesson, while usage is retained globally.
    prefix=f'v41:{kind}:{topic}:'
    for step in range(count):
        index=(seed+step)%count;key=prefix+str(index)
        if key not in used:break
    else:
        # A very long-lived profile cycles only after exhausting its complete set.
        index=seed%count;key=prefix+str(index)
    text=starts[index//len(ends)]+ends[index%len(ends)]
    if kind=='pass' and topic:text+='（'+topic+'）'
    return key,text
